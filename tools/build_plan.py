def meal(text, short, steps, warn="", mode="plan"):
    return {
        "text": text,
        "short": short,
        "steps": steps,
        "warn": warn,
        "mode": mode,
    }


def split_meal(me_text, her_text, me_short, her_short, me_mode, her_mode, steps=None, warn=""):
    return {
        "me": meal(me_text, me_short, steps or [], warn, me_mode),
        "her": meal(her_text, her_short, steps or [], warn, her_mode),
    }


def same_meal(text, short, steps, warn="", mode="plan"):
    one = meal(text, short, steps, warn, mode)
    return {"me": one, "her": one}


